# ==============================
# day1_hello.py —— Day 1：第一行代码
# 井号开头是注释，Python 不执行（相当于 C / Java 的 //）
# ==============================

print("hello, python")     # print 是内置函数，不用 include / import；"hello, python" 是字符串
print("hello", "world")    # 逗号隔开两段内容，打印时自动加一个空格

# --- 没有分号：一行写完，回车就是语句结束 ---
x = 5                      # 不用写 int，直接赋值，Python 自己认类型
print(x)                   # 打印变量不加引号；加了引号 print("x") 打的是字母 x

# --- 引号：单引号双引号完全等价 ---
print('单引号也行')
print("双引号也行")

# --- 缩进是语法，不是美观 ---
# 下面的 if 今天不细讲（Day 4 的内容），只为演示一件事：
# 第二行前面那 4 个空格，干的就是 C / Java 里花括号的活，删掉直接报错
if x > 3:
    print("x 比 3 大")

print("day1 完工")         # 跑到这行说明上面全对
